int aic_find_language(const char *code)
{
    if (code == NULL)
        return -1;
    for (int i = 0; i < AIC_LANG_COUNT; i++) {
        if (strcmp(languages[i].lan_name, code) == 0)
            return i;
    }
    return -1;
}

