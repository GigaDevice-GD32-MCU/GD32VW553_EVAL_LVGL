#include <string.h>

#include "ui_init.h"
#include "screens/screen/screen.h"
#include "screens/screen1/screen_1.h"
#include "screens/screen2/screen_2.h"

ui_manager_t ui_manager;

void ui_manager_init(ui_manager_t *ui, bool auto_del)
{
    memset(ui, 0, sizeof(*ui));
    ui->auto_del = auto_del;
}

void ui_init(void)
{
    ui_manager_init(&ui_manager, true);
    screen_create(&ui_manager);
    screen_1_create(&ui_manager);
    screen_2_create(&ui_manager);
    lv_scr_load(ui_manager.screen.obj);
}

void ui_ensure_screen(void)
{
    if (ui_manager.screen.obj == NULL) {
        screen_create(&ui_manager);
    }
}

void ui_ensure_screen_1(void)
{
    if (ui_manager.screen_1.obj == NULL) {
        screen_1_create(&ui_manager);
    }
}

void ui_ensure_screen_2(void)
{
    if (ui_manager.screen_2.obj == NULL) {
        screen_2_create(&ui_manager);
    }
}

void ui_set_language(lang_type_t lang)
{
    aic_set_language(lang);
    screen_update_language(lang);
    screen_1_update_language(lang);
    screen_2_update_language(lang);
}

lv_obj_t *ui_get_screen_by_name(const char *name)
{
    if (name == NULL) return NULL;
    if (strcmp(name, "screen") == 0) {
        ui_ensure_screen();
        return ui_manager.screen.obj;
    }
    if (strcmp(name, "screen_1") == 0) {
        ui_ensure_screen_1();
        return ui_manager.screen_1.obj;
    }
    if (strcmp(name, "screen_2") == 0) {
        ui_ensure_screen_2();
        return ui_manager.screen_2.obj;
    }
    return NULL;
}
