static void gui_app_gauge_timer_cb(lv_timer_t *timer)
{
    screen_t *screen = &ui_manager.screen;
    lv_obj_t *arcs[] = {
        screen->ui_screen_Arc_1,
        screen->ui_screen_Arc_2,
        screen->ui_screen_Arc_3
    };
    uint32_t index;

    (void)timer;

    if(screen->obj == NULL) {
        return;
    }

    for(index = 0U; index < 3U; index++) {
        gauge_values[index] += gauge_steps[index];
        if(gauge_values[index] >= 90) {
            gauge_values[index] = 90;
            gauge_steps[index] = -gauge_steps[index];
        } else if(gauge_values[index] <= 10) {
            gauge_values[index] = 10;
            gauge_steps[index] = -gauge_steps[index];
        }

        if(arcs[index] != NULL) {
            lv_arc_set_value(arcs[index], gauge_values[index]);
        }
    }
}

