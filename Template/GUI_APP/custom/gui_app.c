/* Advance the wall clock by one second and refresh the label of every created screen. */
static void gui_app_clock_timer_cb(lv_timer_t *timer)
{
    uint32_t hour;
    uint32_t minute;
    uint32_t second;

    (void)timer;

    clock_seconds = (clock_seconds + 1U) % 86400U;
    hour = clock_seconds / 3600U;
    minute = (clock_seconds / 60U) % 60U;
    second = clock_seconds % 60U;

    if(ui_manager.screen.obj != NULL && ui_manager.screen.ui_screen_Label_1_a768 != NULL) {
        lv_label_set_text_fmt(ui_manager.screen.ui_screen_Label_1_a768,
                              "%02d:%02d:%02d", (int)hour, (int)minute, (int)second);
    }
    if(ui_manager.screen_1.obj != NULL && ui_manager.screen_1.ui_screen_Label_1_a768_44bb != NULL) {
        lv_label_set_text_fmt(ui_manager.screen_1.ui_screen_Label_1_a768_44bb,
                              "%02d:%02d:%02d", (int)hour, (int)minute, (int)second);
    }
    if(ui_manager.screen_2.obj != NULL && ui_manager.screen_2.ui_screen_Label_1_a768_44bb_ba53 != NULL) {
        lv_label_set_text_fmt(ui_manager.screen_2.ui_screen_Label_1_a768_44bb_ba53,
                              "%02d:%02d:%02d", (int)hour, (int)minute, (int)second);
    }
}

/* Cycle ui_screen_1_Dropdown_1 down by one option, wrapping back to the first one.
 * lv_dropdown_set_selected() does not notify the widget's subscribers, so the
 * LV_EVENT_VALUE_CHANGED handlers that apply the language are sent explicitly. */
static void gui_app_dropdown_select_next(void)
{
    lv_obj_t *dropdown;
    uint16_t option_cnt;
    uint16_t selected;

    ui_ensure_screen_1();
    dropdown = ui_manager.screen_1.ui_screen_1_Dropdown_1;
    if(dropdown == NULL) {
        return;
    }

    option_cnt = lv_dropdown_get_option_cnt(dropdown);
    if(option_cnt == 0U) {
        return;
    }

    selected = (uint16_t)((lv_dropdown_get_selected(dropdown) + 1U) % option_cnt);
    lv_dropdown_set_selected(dropdown, selected);
    lv_event_send(dropdown, LV_EVENT_VALUE_CHANGED, NULL);
}

