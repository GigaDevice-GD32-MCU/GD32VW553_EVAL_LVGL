void gui_app_button_init(void)
{
    button_stable_level = BUTTON_LEVEL_RELEASED;
    button_last_sample = BUTTON_LEVEL_RELEASED;
    button_sample_tick = lv_tick_get();
    button_press_tick = button_sample_tick;
}

void gui_app_button_task(void)
{
    uint8_t sample = (gd_eval_key_state_get(KEY_TAMPER_WAKEUP) != 0U) ?
                     BUTTON_LEVEL_RELEASED : BUTTON_LEVEL_PRESSED;
    uint32_t now = lv_tick_get();

    /* restart the debounce window whenever the raw level changes */
    if(sample != button_last_sample) {
        button_last_sample = sample;
        button_sample_tick = now;
        return;
    }

    if((uint32_t)(now - button_sample_tick) < BUTTON_DEBOUNCE_MS) {
        return;
    }

    if(sample == button_stable_level) {
        return;
    }
    button_stable_level = sample;

    if(sample == BUTTON_LEVEL_PRESSED) {
        /* remember when the key went down so the release can be classified */
        button_press_tick = now;
    } else {
        /* act on release: a long hold cycles the dropdown, a short tap flips the page */
        if((uint32_t)(now - button_press_tick) >= BUTTON_LONG_PRESS_MS) {
            gui_app_dropdown_select_next();
        } else {
            gui_app_process_button();
        }
    }
}

void gui_app_process_button(void)
{
    if(current_page == GUI_PAGE_HOME) {
        ui_ensure_screen_1();
        lv_scr_load(ui_manager.screen_1.obj);
        current_page = GUI_PAGE_CONTROL;
    } else if(current_page == GUI_PAGE_CONTROL) {
        ui_ensure_screen_2();
        lv_scr_load(ui_manager.screen_2.obj);
        current_page = GUI_PAGE_SETTINGS;
    } else {
        ui_ensure_screen();
        lv_scr_load(ui_manager.screen.obj);
        current_page = GUI_PAGE_HOME;
    }
}
